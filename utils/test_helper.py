def add_numbers(a, b):
    """
    Add two numbers together and return their sum.

    Args:
        a: The first number to add (int or float)
        b: The second number to add (int or float)

    Returns:
        The sum of a and b (int or float)

    Example:
        >>> add_numbers(5, 3)
        8
        >>> add_numbers(2.5, 3.7)
        6.2
    """
    return a + b
